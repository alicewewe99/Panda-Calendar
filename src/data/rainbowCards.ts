export function getRandomRainbowCard(chakra?: ChakraColor): RainbowCard {
  const pool = chakra ? RAINBOW_CARDS.filter(c => c.chakra === chakra) : RAINBOW_CARDS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
